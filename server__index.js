require('dotenv').config({ path: require('path').join(__dirname, '../.env') });
const path = require('path');
const http = require('http');
const express = require('express');
const cors = require('cors');
const { Server } = require('socket.io');
const db = require('./db');
const auth = require('./auth');
const shop = require('./shop');
const admin = require('./admin');
const game = require('./game');
const PORT = +process.env.PORT || 3000;
if (!process.env.JWT_SECRET) console.warn('[!] JWT_SECRET не задан в .env — используется небезопасное значение по умолчанию');
const app = express();
app.use(cors());
app.use(express.json({ limit: '6mb' }));
app.use('/api/auth', auth.router);
app.use('/api/shop', shop.router);
app.use('/api', admin.router);
app.get('/api/info', (req, res) => { res.set('Cache-Control', 'no-store'); res.json({ name: 'Официальный сервер #1', players: game.G.players.size, max: game.MAX_PLAYERS, version: '1.0.0' }); });
app.use('/shared', express.static(path.join(__dirname, '../shared')));
app.use(express.static(path.join(__dirname, '../client')));
const server = http.createServer(app);
const io = new Server(server, { cors: { origin: '*' }, pingInterval: 5000, pingTimeout: 10000 });
game.init(io).then(() => {
  server.listen(PORT, '0.0.0.0', () => console.log(`[server] http://localhost:${PORT}`));
}).catch(e => { console.error(e); process.exit(1); });
const shutdown = () => { try { game.saveAll(); } catch {} process.exit(0); };
process.on('SIGINT', shutdown); process.on('SIGTERM', shutdown);
